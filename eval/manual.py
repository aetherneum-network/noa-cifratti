"""Hand-planted part of the blind evaluation: twenty inert values hidden by a different hand.

    python eval/manual.py values --seed N --runner NAME
    python eval/manual.py score  --seed N --runner NAME --repo DIR --hidden FILE [--record --run-date ISO] [--json OUT]

``values`` prints twenty inert values drawn from the seed (formats of SYNTHETIC.md) and writes a
form, ``build/blind-manual-N/hidden.json``. The runner hides the values by hand, with any technique,
in a synthetic repository - for instance one generated by ``eval/score.py --suite blind`` - and then
fills the form: for each value ``hidden`` (true/false), ``form`` and ``where`` (free text).

``form`` is ``plain`` when the value sits, contiguous and unmodified, in the way COVERAGE.md
declares as covered (for a password: assigned to a key that names a secret; for a connection URI: the
URI as printed), in a text file of the working tree or of the history. Anything else - split,
encoded, reversed, inside an archive - is ``other``: outside the promise, and reported as such.

``score`` scans the repository and answers three questions: were the ``plain`` values found (by
exact fingerprint), was the repository ever called CLEAN with a ``plain`` value in it (the
never-event), and does any value appear in clear in the report. Nothing here measures a real system.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
for entry in (str(ROOT), str(ROOT / "eval")):
    if entry not in sys.path:
        sys.path.insert(0, entry)

from corpus import fakes, generate, gold  # noqa: E402
from noascan import report  # noqa: E402
from noascan.scan import scan  # noqa: E402
import score as harness  # noqa: E402

COUNT = 20
DOMAIN = "blind-manual.example"
HINT = {
    "assigned_password": "a password: 'plain' only when assigned to a key that names a secret",
    "connection_uri_password": "a connection URI: 'plain' when the URI is written as printed",
    "armored_key_block": "a key block: 'plain' when the lines are kept together, in order",
}


def plants(seed: int, count: int = COUNT) -> list[dict[str, str]]:
    """The values of a seed: a pure function, so the scorer needs no file that holds them."""
    out = []
    for i in range(count):
        cls = fakes.SECRET_CLASSES[i % len(fakes.SECRET_CLASSES)]
        rng = random.Random(f"noa-blind-manual/v1/{seed}/{i}")
        if cls == "connection_uri_password":
            shown, value = fakes.connection_uri(rng, DOMAIN)
        else:
            shown = value = fakes.make(cls, rng, DOMAIN)
        fp = gold.block_fingerprint(value) if cls == "armored_key_block" else gold.fingerprint(value)
        out.append({"id": f"M{i + 1:02d}", "class": cls, "value": value, "shown": shown, "fingerprint": fp})
    return out


def form(seed: int, runner: str) -> dict[str, Any]:
    return {"seed": seed, "runner": runner, "note": "fill hidden, form (plain|other) and where for each value",
            "plants": [{"id": p["id"], "class": p["class"], "fingerprint": p["fingerprint"], "hidden": False,
                        "form": "", "where": ""} for p in plants(seed)]}


def score(seed: int, repo: Path, hidden: dict[str, Any], as_of: str) -> dict[str, Any]:
    if hidden.get("seed") != seed:
        raise ValueError("the form was written for another seed")
    values = {p["id"]: p for p in plants(seed)}
    out = scan(repo, as_of)
    text = report.dumps(out) + report.summary(out)
    found = {(f["class"], f["fingerprint"]) for f in out["findings"] if f["kind"] == "secret"}
    rows, leaks = [], 0
    for entry in hidden["plants"]:
        p = values[entry["id"]]
        if not entry.get("hidden"):
            continue
        if entry.get("form") not in ("plain", "other"):
            raise ValueError(f"{entry['id']}: form must be 'plain' or 'other'")
        needles = [ln for ln in p["value"].split("\n") if ln and not ln.startswith("-----")]
        leaks += sum(1 for n in needles if n in text)
        rows.append({"id": p["id"], "class": p["class"], "form": entry["form"], "fingerprint": p["fingerprint"],
                     "found_as_secret": (p["class"], p["fingerprint"]) in found})
    plain = [r for r in rows if r["form"] == "plain"]
    other = [r for r in rows if r["form"] == "other"]
    clean = out["verdict"] == "CLEAN"
    return {
        "suite": "blind-manual", "seed": seed, "as_of": as_of, "rules": out["rules"],
        "statement": "internal consistency on synthetic data; no claim about any real system",
        "hidden": len(rows), "plain": len(plain), "plain_found": sum(r["found_as_secret"] for r in plain),
        "other": len(other), "other_found_as_secret": sum(r["found_as_secret"] for r in other),
        "verdict": out["verdict"], "counters": out["counters"],
        "never_event": int(clean and bool(plain)),
        "clean_with_only_out_of_coverage_secret": int(clean and not plain and bool(other)),
        "secret_values_in_reports": leaks, "plants": rows,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Hand-planted blind evaluation (synthetic data only).")
    ap.add_argument("cmd", choices=["values", "score"])
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--runner", required=True, help="who runs it (a different hand than the author)")
    ap.add_argument("--repo", type=Path)
    ap.add_argument("--hidden", type=Path)
    ap.add_argument("--json", type=Path)
    ap.add_argument("--record", action="store_true")
    ap.add_argument("--run-date")
    ap.add_argument("--note", default="")
    args = ap.parse_args(argv)
    if args.seed in harness.SEEDS["author_seeds"].values():
        print("error: this seed was used by the author during development; choose another one", file=sys.stderr)
        return 64
    ok, freeze = harness.frozen_state()
    if not ok:
        print(f"error: not a blind run: {freeze}", file=sys.stderr)
        return 64
    if args.cmd == "values":
        path = ROOT / "build" / f"blind-manual-{args.seed}" / "hidden.json"
        report.write(path, form(args.seed, args.runner))
        for p in plants(args.seed):
            print(f"{p['id']}  {p['class']}  ({HINT.get(p['class'], 'a token: plain when written as printed')})")
            print("\n".join("    " + ln for ln in p["shown"].split("\n")))
        print(f"\nform written: build/blind-manual-{args.seed}/hidden.json ({COUNT} values; inert, see SYNTHETIC.md)")
        return 0
    if not args.repo or not args.hidden or (args.record and not args.run_date):
        print("error: score needs --repo and --hidden; --record needs --run-date (the clock is never read)", file=sys.stderr)
        return 64
    try:
        res = score(args.seed, args.repo, json.loads(args.hidden.read_text(encoding="utf-8")), generate.CONFIG["as_of"])
    except (OSError, ValueError, KeyError) as exc:
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 64
    print(f"hand-planted blind run, seed {args.seed}: {res['hidden']} hidden; plain {res['plain_found']}/{res['plain']} found; "
          f"other {res['other_found_as_secret']}/{res['other']} found as secret")
    print(f"  verdict {res['verdict']}; never-event (CLEAN with a plain value): {res['never_event']}; "
          f"CLEAN with only out-of-coverage values: {res['clean_with_only_out_of_coverage_secret']}; "
          f"values in the report: {res['secret_values_in_reports']}")
    if args.json:
        report.write(args.json, res)
    if args.record:
        path = ROOT / "eval" / "history.json"
        hist = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"runs": []}
        numbers = {k: res[k] for k in ("hidden", "plain", "plain_found", "other", "other_found_as_secret", "verdict",
                                       "never_event", "clean_with_only_out_of_coverage_secret", "secret_values_in_reports")}
        hist["runs"].append({"run": len(hist["runs"]) + 1, "run_date": args.run_date, "suite": "blind-manual", "seed": args.seed,
                             "perturbed": False, "runner": args.runner, "freeze_commit": freeze,
                             "sizes": {"hand_planted": res["hidden"]},
                             "rules": [{"file": n, "sha256_12": v["sha256"][:12]} for n, v in res["rules"].items()],
                             "numbers": numbers, "note": args.note})
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(json.dumps(hist, indent=2, ensure_ascii=True) + "\n")
    return 0 if res["never_event"] == 0 and res["secret_values_in_reports"] == 0 and res["plain_found"] == res["plain"] else 1


if __name__ == "__main__":
    sys.exit(main())
